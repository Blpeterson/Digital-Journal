import { expect, test } from '@playwright/test'

test('creates a notebook and preserves spread content across the responsive threshold', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173')
  await page.getByRole('button', { name: 'New notebook', exact: true }).click()
  await page.getByLabel('Title').fill('Visual acceptance')
  await page.getByRole('button', { name: 'Create' }).click()
  await page.getByRole('button', { name: 'Visual acceptance' }).click()
  const editor = page.locator('.tiptap').first()
  await editor.fill('The first line stays with the page.')
  const editorBox = await editor.boundingBox()
  if (!editorBox) throw new Error('Editor was not visible')
  await page.mouse.click(editorBox.x + 80, editorBox.y + 30 * 5 + 8)
  await page.keyboard.type('This starts on the clicked line.')
  expect(await editor.locator('p').count()).toBeGreaterThanOrEqual(3)

  await page.keyboard.press('Control+A')
  await page.getByLabel('Font').first().selectOption('Cursive Note')
  await expect(editor.locator('[style*="font-family"]').filter({ hasText: 'This starts on the clicked line.' })).toHaveCount(1)

  await page.getByRole('button', { name: 'flower' }).click()
  const pageBox = await page.locator('.notebook-page').first().boundingBox()
  if (!pageBox) throw new Error('Notebook page was not visible')
  await page.mouse.move(pageBox.x + 360, pageBox.y + 400)
  await page.mouse.click(pageBox.x + 360, pageBox.y + 400)
  const sticker = page.locator('.decoration.sticker')
  await expect(sticker).toHaveCount(1)
  await sticker.hover()
  await sticker.locator('.decoration-controls span').last().dispatchEvent('pointerdown')
  await expect(sticker).toHaveCSS('transform', /matrix/)
  await sticker.locator('.decoration-controls span').first().dispatchEvent('pointerdown')
  const beforeDrag = await sticker.boundingBox()
  await sticker.hover()
  await page.mouse.down()
  await page.mouse.move(pageBox.x + 460, pageBox.y + 500, { steps: 5 })
  await page.mouse.up()
  const afterDrag = await sticker.boundingBox()
  expect(afterDrag!.x).toBeGreaterThan(beforeDrag!.x + 50)
  await expect(page.locator('.notebook-page')).toHaveCount(2)
  await page.setViewportSize({ width: 800, height: 900 })
  await expect(page.locator('.notebook-page:visible')).toHaveCount(1)
  await expect(editor).toContainText('The first line stays with the page.')
  await expect(page).toHaveScreenshot('lined-page-responsive.png', { animations: 'disabled' })
})

test('print document includes both covers and every page', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173')
  await page.getByRole('button', { name: 'New notebook', exact: true }).click()
  await page.getByLabel('Title').fill('Complete export')
  await page.locator('input[type="range"]').fill('20')
  await page.getByRole('button', { name: 'Create' }).click()
  await page.waitForTimeout(650)
  const notebook = await page.evaluate(() => JSON.parse(localStorage.getItem([...Object.keys(localStorage)].find(key => key.startsWith('notebook:'))!) ?? 'null'))
  await page.evaluate(value => localStorage.setItem('print:notebook', JSON.stringify(value)), notebook)
  await page.goto('http://127.0.0.1:5173?print=1')
  const frontCover = page.locator('.print-cover.front')
  await expect(frontCover).toHaveCount(1)
  await expect(frontCover).toHaveScreenshot('pdf-front-cover.png', { animations: 'disabled' })
  await expect(page.locator('.print-document .notebook-page')).toHaveCount(20)
  await expect(page.locator('.print-cover.back')).toHaveCount(1)
})
